// Accessories (16x14), one per direction. Built from filled shapes, auto outlined, exported as row strings.
const W = 16;
const H = 14;
const R = (x0, y0, x1, y1) => {
  const a = [];
  for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) a.push([x, y]);
  return a;
};
const P = (...p) => p;
const mir = (a) => a.map(([x, y]) => [15 - x, y]);
const minus = (a, b) => a.filter(([x, y]) => !b.some(([bx, by]) => bx === x && by === y));
const rim = (x0, y0, x1, y1) => minus(R(x0, y0, x1, y1), R(x0 + 1, y0 + 1, x1 - 1, y1 - 1));

const draw = (parts, noOutline) => {
  const g = Array.from({ length: H }, () => Array(W).fill('.'));
  for (const [cells, ch] of parts) for (const [x, y] of cells) if (x >= 0 && x < W && y >= 0 && y < H) g[y][x] = ch;
  if (!noOutline) {
    const f = (x, y) => x >= 0 && y >= 0 && x < W && y < H && g[y][x] !== '.' && g[y][x] !== 'O';
    const add = [];
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (g[y][x] === '.' && (f(x - 1, y) || f(x + 1, y) || f(x, y - 1) || f(x, y + 1))) add.push([x, y]);
    for (const [x, y] of add) g[y][x] = 'O';
  }
  return { w: W, h: H, rows: g.map((r) => r.join('')) };
};

const dome = (x0, x1, y0, y1) => {
  const a = R(x0, y0, x1, y1);
  return minus(a, P([x0, y0], [x1, y0]));
};
const bowLoop = (x0, x1) => minus(R(x0, 1, x1, 4), P([x0, 1], [x1, 4], [x0 === 8 ? 8 : x0, 4]));

