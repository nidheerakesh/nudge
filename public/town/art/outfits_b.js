// Rows are built with tiny helpers but exported as plain row strings.
const R = (x, s) => '.'.repeat(x) + s + '.'.repeat(16 - x - s.length);
const E = () => '.'.repeat(16);
const put = (rows, y, x, s) => {
  const r = rows[y];
  rows[y] = r.slice(0, x) + s + r.slice(x + s.length);
};
const sp = (rows, w, h) => ({ w, h, rows });

